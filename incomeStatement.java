    public void loadIncomeStatements() {
        // Format dates for SQL if they are not null
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        String dateFilter = ""; // Default: No date filter
        if (startDate != null && endDate != null) {
            String startDateStr = sdf.format(startDate);
            String endDateStr = sdf.format(endDate);
            dateFilter = " AND `date` BETWEEN '" + startDateStr + "' AND '" + endDateStr + "'";
        }

        try {
            // Queries with optional date filtering
            String revenueQuery = "SELECT `amount` FROM `accounting_entries` WHERE `type_id`='1'" + dateFilter;
            String expenseQuery = "SELECT `amount` FROM `accounting_entries` WHERE `type_id`='2'" + dateFilter;
            String netIncomeQuery = "SELECT "
                    + "    (SELECT SUM(`amount`) FROM `accounting_entries` WHERE `type_id`='1'" + dateFilter + ") - "
                    + "    (SELECT SUM(`amount`) FROM `accounting_entries` WHERE `type_id`='2'" + dateFilter + ") AS `net_income`";

            // Execute queries
            ResultSet revenueResult = MySQL2.executeSearch(revenueQuery);
            ResultSet expenseResult = MySQL2.executeSearch(expenseQuery);
            ResultSet netIncomeResult = MySQL2.executeSearch(netIncomeQuery);

            // Clear and prepare table model
            DefaultTableModel model = (DefaultTableModel) jTable3.getModel();
            model.setRowCount(0);

            // Populate row-by-row for revenue and expense entries
            while (revenueResult.next() && expenseResult.next()) {
                Vector<String> row = new Vector<>();
                String revenueAmount = revenueResult.getString("amount");
                String expenseAmount = expenseResult.getString("amount");
                String netIncome = String.valueOf(Double.parseDouble(revenueAmount) - Double.parseDouble(expenseAmount));

                row.add(revenueAmount); // Revenue
                row.add(expenseAmount); // Expenses
                row.add(netIncome);     // Row-wise Net Income
                model.addRow(row);
            }

            // Display total net income at the bottom of the table
            if (netIncomeResult.next()) {
                String totalNetIncome = netIncomeResult.getString("net_income");
                Vector<String> totalRow = new Vector<>();
                totalRow.add("Total");      // Label for total
                totalRow.add("");           // Empty cell for alignment
                totalRow.add(totalNetIncome); // Total Net Income
                model.addRow(totalRow);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

