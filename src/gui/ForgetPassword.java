    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String username = jTextField1.getText();
        String nic = jTextField2.getText();
      
        if (username.isBlank()) {
            JOptionPane.showMessageDialog(this, "Please enter your username", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (nic.isBlank()) {
            JOptionPane.showMessageDialog(this, "Please enter your Password", "Warning", JOptionPane.WARNING_MESSAGE);        
        } else {
            try {
                ResultSet rs = MySQL.executeSearch("SELECT * FROM `user` WHERE `username` = '" + username + "' AND `nic` = '" + nic + "'");
                if (rs.next()) {
                    jButton1.setText("Correct");
                    jButton1.setForeground(Color.green);
                    jPasswordField1.setEditable(true);
                    jPasswordField2.setEditable(true);
                    jPasswordField1.grabFocus();
                    jTextField1.setEditable(false);
                } else {
                    jButton1.setText("Incorrect");
                    jButton1.setForeground(Color.red);
                }
            } catch (Exception ex) {
                ex.printStackTrace();
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String Newpassword = String.valueOf(jPasswordField1.getPassword());
        String Repassword = String.valueOf(jPasswordField2.getPassword());
        
        if (jButton1.getText().equals("Coreect")) {
            JOptionPane.showMessageDialog(this,"Please checked Username and NIC", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (Newpassword.isBlank()) {
            JOptionPane.showMessageDialog(this, "Please enter New password", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (Newpassword.length() < 8 || Newpassword.length() > 20) {
            JOptionPane.showMessageDialog(this, "Password must be more than 8 characters and less than 20 characters", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (Repassword.isBlank()) {
            JOptionPane.showMessageDialog(this, "Please Re-enter New Password", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (!Newpassword.equals(Repassword)) {
            JOptionPane.showMessageDialog(this, "New Password and Re-type Password doesn't match..!", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {
            try {
                MySQL.executeIUD("UPDATE `user` SET `password` = '" + Newpassword + "' WHERE `username` = '" + jTextField1.getText() + "'");
                JOptionPane.showMessageDialog(this, jTextField1.getText() + ": Password has update..!", "Success", JOptionPane.INFORMATION_MESSAGE);
                reset();
            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

