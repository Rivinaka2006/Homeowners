    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        if (jComboBox1.getSelectedItem().equals("Select")) {
            JOptionPane.showMessageDialog(this, "Please enter User Type", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {
            try {
                ResultSet rs = MySQL.executeSearch("SELECT * FROM `user` WHERE `user_type_id` = '" + TypeMap.get(jComboBox1.getSelectedItem()) + "' AND `id` = '" + jLabel3.getText() + "'");
                if (rs.next()) {
                    JOptionPane.showMessageDialog(this, "User Type has Already Exisits", "Warning", JOptionPane.WARNING_MESSAGE);
                } else {
                    MySQL.executeIUD("UPDATE `user` SET `user_type_id` = '" + TypeMap.get(jComboBox1.getSelectedItem()) + "' AND `status_id` = '"+userStatus+"' WHERE `id` = '" + jLabel3.getText() + "'");
                    JOptionPane.showMessageDialog(this, "Update Sucessfully", "Success", JOptionPane.INFORMATION_MESSAGE);
                }
            } catch (Exception e) {
                e.printStackTrace();
            }
        }

    }//GEN-LAST:event_jButton1ActionPerformed

    private void jToggleButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButton1ActionPerformed
        // TODO add your handling code here:
       if(jToggleButton1.getText() == "Active"){
           userStatus = "1";          
       }
       if(jToggleButton1.getText() == "Deactive"){
             userStatus = "2";              
       }
       if(jToggleButton1.isSelected()){
          if(userStatus == "1"){
              jToggleButton1.setText("Deactive");
          }
       if(userStatus == "2"){
              jToggleButton1.setText("Active");
          }
       
       }
    }//GEN-LAST:event_jToggleButton1ActionPerformed

