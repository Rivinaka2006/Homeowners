    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if (jTable1.getSelectedRowCount() == 1) {
            String line1 = jTextField1.getText();
            String line2 = jTextField2.getText();
            String city = String.valueOf(jComboBox1.getSelectedItem());

            if (line1.isBlank()) {
                JOptionPane.showMessageDialog(this, "Please enter address line 1", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (line1.length() > 45) {
                JOptionPane.showMessageDialog(this, "Address line 1 should be less than 45 characters", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (line2.isBlank()) {
                JOptionPane.showMessageDialog(this, "Please enter address line 2", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (line2.length() > 45) {
                JOptionPane.showMessageDialog(this, "Address line 2 should be less than 45 characters", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (city.equals("Select")) {
                JOptionPane.showMessageDialog(this, "Please select City", "Warning", JOptionPane.WARNING_MESSAGE);
            } else {
                try {
                    boolean isFound = false;
                    for (int i = 0; i < jTable1.getRowCount(); i++) {
                        String getLine1 = String.valueOf(jTable1.getValueAt(i, 1));
                        String getLine2 = String.valueOf(jTable1.getValueAt(i, 2));
                        String getCity = String.valueOf(jTable1.getValueAt(i, 3));
                        if (getLine1.equals(line1) && getLine2.equals(line2) && getCity.equals(city)) {
                            JOptionPane.showMessageDialog(this, "Address already added", "Warning", JOptionPane.WARNING_MESSAGE);
                            isFound = true;
                            break;
                        }
                    }
                    //update
                    if (!isFound) {
                        MySQL.executeIUD("UPDATE `user_address` SET `line_1` = '" + line1 + "' , `line_2` = '" + line2 + "',`city_id` = '" + cityMap.get(city) + "' WHERE `id` = '" + String.valueOf(jTable1.getValueAt(jTable1.getSelectedRow(), 0)) + "' ");
                        JOptionPane.showMessageDialog(this, "Update Successfully", "Success", JOptionPane.INFORMATION_MESSAGE);
                        loadAddress();
                        reset();
                        jButton1.setEnabled(true);
                    }
                } catch (Exception e) {
                    e.printStackTrace();

                }
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String line1 = jTextField1.getText();
        String line2 = jTextField2.getText();
        String city = String.valueOf(jComboBox1.getSelectedItem());
        if (line1.isBlank()) {
            JOptionPane.showMessageDialog(this, "Please enter Address Line 1", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (line1.length() > 45) {
            JOptionPane.showMessageDialog(this, "Address line 1 should be less than 45 characters", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (line2.isBlank()) {
            JOptionPane.showMessageDialog(this, "Please enter Address Line 2", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (line2.length() > 45) {
            JOptionPane.showMessageDialog(this, "Address line 2 should be less than 45 characters", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (city.equals("Select")) {
            JOptionPane.showMessageDialog(this, "Please select City", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {
            try {
                boolean isFound = false;
                for (int i = 0; i < jTable1.getRowCount(); i++) {
                    String getLine1 = String.valueOf(jTable1.getValueAt(i, 1));
                    String getLine2 = String.valueOf(jTable1.getValueAt(i, 2));
                    String getCity = String.valueOf(jTable1.getValueAt(i, 3));
                    if (getLine1.equals(line1) && getLine2.equals(line2) && getCity.equals(city)) {
                        JOptionPane.showMessageDialog(this, "Address already added", "Warning", JOptionPane.WARNING_MESSAGE);
                        isFound = true;
                        break;
                    }
                }
                if (!isFound) {
                    MySQL.executeIUD("INSERT INTO `user_address` (`line_1`,line_2,`city_id`,`user_id`) VALUES ('" + line1 + "','" + line2 + "','" + cityMap.get(city) + "','" + jLabel2.getText() + "')");
                    JOptionPane.showMessageDialog(this, "Address Added Successfully", "Success", JOptionPane.INFORMATION_MESSAGE);
                    loadAddress();
                    reset();
                }
            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        if (evt.getClickCount() == 1) {
            jTextField1.setText(String.valueOf(jTable1.getValueAt(jTable1.getSelectedRow(), 1)));
            jTextField2.setText(String.valueOf(jTable1.getValueAt(jTable1.getSelectedRow(), 2)));
            jComboBox1.setSelectedItem(String.valueOf(jTable1.getValueAt(jTable1.getSelectedRow(), 3)));
            jButton1.setEnabled(false);
        }
        if (evt.getClickCount() == 2) {
            jButton3.setEnabled(true);
            jButton3.setBackground(Color.red);
        }
    }//GEN-LAST:event_jTable1MouseClicked

