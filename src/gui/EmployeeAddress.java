    private void loadCity() {
        try {
            ResultSet rs = MySQL.executeSearch("SELECT * FROM `city`");
            Vector<String> v = new Vector<>();
            v.add("Select");
            while (rs.next()) {
                v.add(rs.getString("name"));
                cityMap.put(rs.getString("name"), rs.getString("id"));
            }
            jComboBox1.setModel(new DefaultComboBoxModel(v));
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    private void loadAddress() {
        try {
            DefaultTableModel m = (DefaultTableModel) jTable1.getModel();
            ResultSet rs = MySQL.executeSearch("SELECT * FROM `user_address` INNER JOIN `city` ON `city`.`id` = `user_address`.`city_id`");
            m.setRowCount(0);
            while (rs.next()) {
                Vector<String> v = new Vector<>();
                v.add(rs.getString("id"));
                v.add(rs.getString("line_1"));
                v.add(rs.getString("line_2"));
                v.add(rs.getString("city.name"));
                m.addRow(v);
            }
            jTable1.setModel(m);
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

