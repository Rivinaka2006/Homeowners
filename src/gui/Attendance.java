    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String uid = jFormattedTextField1.getText();

        if (uid.isBlank()) {
            JOptionPane.showMessageDialog(this, "Please enter Employee Id", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {
            String dateTime = new SimpleDateFormat("yyyy-MM-dd").format(new Date());
            String time = new SimpleDateFormat("HH:mm:ss").format(new Date());

            try {
                ResultSet rs = MySQL.executeSearch("SELECT * FROM `attedance` WHERE `user_id` = '" + uid + "' AND `present_day` = '" + dateTime + "'");
                if (rs.next()) {
                    JOptionPane.showMessageDialog(this, jLabel3.getText() + " has already Attendance marked !!", "Success", JOptionPane.INFORMATION_MESSAGE);
                    reset();
                } else {
                    if (jLabel7.getText().equals("Active")) {
                        MySQL.executeIUD("INSERT INTO `attedance` (`present_day`,`time`,`user_id`,`working_status_id`) VALUES('" + dateTime + "','" + time + "','" + uid + "','1')");
                        JOptionPane.showMessageDialog(this, "Attendance has marked!", "Warning", JOptionPane.INFORMATION_MESSAGE);
reset();
                    }
                }
            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

