    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        String units = jTextField2.getText();

        if (units.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter Units", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {

            try {
                ResultSet rs = MySQL.executeSearch("SELECT * FROM `unit` WHERE `name` = '" + units + "'");

                if (rs.next()) {
                    JOptionPane.showMessageDialog(this, "This Units already Added", "Warning", JOptionPane.WARNING_MESSAGE);
                } else {

                    MySQL.executeIUD("INSERT INTO `unit` (`name`) VALUES ('" + units + "')");
                    loadTable("");
                    reset();
                    JOptionPane.showMessageDialog(this, "Unit added Successfuly", "Done", JOptionPane.INFORMATION_MESSAGE);

                }
            } catch (Exception e) {
                e.printStackTrace();
            }

        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

        String id = jTextField1.getText();
        String units = jTextField2.getText();

        if (units.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter the Unit", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {

            try {

                ResultSet rs = MySQL.executeSearch("SELECT * FROM `unit` WHERE `name` = '" + units + "'");

                if (rs.next()) {
                    JOptionPane.showMessageDialog(this, "This Units already Added", "Warning", JOptionPane.WARNING_MESSAGE);
                } else {

                    MySQL.executeIUD("UPDATE `unit` SET `name` = '" + units + "' WHERE `id` = '" + id + "'");
                    loadTable("");
                    reset();
                    JOptionPane.showMessageDialog(this, "Unit update Successfuly", "Done", JOptionPane.INFORMATION_MESSAGE);

                }

            } catch (Exception e) {
                e.printStackTrace();
            }
    }//GEN-LAST:event_jButton2ActionPerformed
    }
