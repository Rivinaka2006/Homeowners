    private void loadTable(String fromThis) {

        try {

            ResultSet rs = MySQL.executeSearch("SELECT * FROM `unit` WHERE `name` LIKE '%" + fromThis + "%'");
            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);

            while (rs.next()) {
                Vector v = new Vector();
                v.add(rs.getString("id"));
                v.add(rs.getString("name"));

                dtm.addRow(v);
                jTable1.setModel(dtm);

            }

        } catch (Exception e) {
            e.printStackTrace();
        }

    }

