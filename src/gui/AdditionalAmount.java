    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
       String additionalAmount = jFormattedTextField1.getText();
       String userID = jLabel3.getText();
        if(additionalAmount.isBlank()){
            JOptionPane.showMessageDialog(this,"Please enter Additional Amount", "Warning",JOptionPane.WARNING_MESSAGE);
        }else{
            try {
                ResultSet rs = MySQL.executeSearch("SELECT * FROM `addtional_salary` WHERE `user_id` = '"+userID+"'");
                if(rs.next()){
                    if(Double.parseDouble(additionalAmount) == Double.parseDouble(rs.getString("amount"))){
                        JOptionPane.showMessageDialog(this,"Same Amount yet", "Warning",JOptionPane.WARNING_MESSAGE);
                    }else{
                        MySQL.executeIUD("UPDATE `addtional_salary` SET `amount` = '"+additionalAmount+"' WHERE `user_id` = '"+userID+"'");
                         JOptionPane.showMessageDialog(this,"Additional Amount Update Sucessfully","Success",JOptionPane.INFORMATION_MESSAGE);
                    }
                }else{
                    Date date = new Date();
                    SimpleDateFormat format = new SimpleDateFormat("yyyy-MM-dd");
                    MySQL.executeIUD("INSERT INTO `addtional_salary` (`date`,`amount`,`user_id`) VALUES('"+format.format(date)+"','"+additionalAmount+"','"+userID+"')");
                    JOptionPane.showMessageDialog(this,"Additional Amount Added Sucessfully","Success",JOptionPane.INFORMATION_MESSAGE);
                }
            } catch (Exception e) {
            e.printStackTrace();
            }
            
        }
    }//GEN-LAST:event_jButton2ActionPerformed

