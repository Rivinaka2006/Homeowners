    private void loadAttedance() {
        Date Fromdate = jDateChooser1.getDate();
        Date Todate = jDateChooser2.getDate();
        if (Fromdate == null) {
            JOptionPane.showMessageDialog(this, "Please select From Date", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (Todate == null) {
            JOptionPane.showMessageDialog(this, "Please select To Date", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {
            SimpleDateFormat format = new SimpleDateFormat("yyyy-MM-dd");
            DefaultTableModel m = (DefaultTableModel) jTable1.getModel();
            m.setRowCount(0);
            try {
                String query = "SELECT COUNT(*) OVER() As dayCount,`attedance`.`id`,`attedance`.`present_day`,`time`,`working_status`.`status` FROM `attedance`"
                        + " INNER JOIN `working_status` ON `working_status`.`id` = `attedance`.`working_status_id` "
                        + "WHERE (`attedance`.`present_day` >= '" + format.format(Fromdate) + "' AND `attedance`.`present_day` <= '" + format.format(Todate) + "') "
                        + "AND (`user_id` = '" + jLabel3.getText() + "')";
                ResultSet rs = MySQL.executeSearch(query);
                while (rs.next()) {
                    Vector<String> v = new Vector<>();
                    v.add(rs.getString("id"));
                    v.add(rs.getString("present_day"));
                    v.add(rs.getString("time"));
                    v.add(rs.getString("working_status.status"));
                    m.addRow(v);
                    jLabel10.setText(rs.getString("dayCount"));
                }
                jTable1.setModel(m);

                query += " AND `working_status_id` = '2'";
                ResultSet rs1 = MySQL.executeSearch(query);
                if (rs1.next()) {
                    jLabel12.setText(rs1.getString("dayCount"));
                } else {
                    jLabel12.setText("0");
                }
                Integer allDays = Integer.valueOf(jLabel10.getText());
                Integer presentDays = Integer.valueOf(jLabel12.getText());
                Integer absent = allDays - presentDays;
                jLabel14.setText(String.valueOf(absent));
            } catch (Exception e) {
                e.printStackTrace();
            }
        }

    }

