    private void jFormattedTextField10KeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_jFormattedTextField10KeyReleased

        String total = jLabel72.getText();
        String payment = jFormattedTextField10.getText();

        if (payment.isBlank()) {
            payment = "0";
        } else if (!payment.matches("^(0|[1-9]\\d*)?(\\.\\d+)?(?<=\\d)$")) {

            jLabel73.setText("INVALID");
            jLabel73.setForeground(Color.red);

        } else {

            double balance = Double.parseDouble(payment) - Double.parseDouble(total);
            jLabel73.setText(String.valueOf(balance));
            jLabel73.setForeground(Color.black);

        }


    }//GEN-LAST:event_jFormattedTextField10KeyReleased

    private void jButton20ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton20ActionPerformed

        String grnID = jTextField16.getText();
        String supplierID = jTextField17.getText();
        int userID = Integer.parseInt(jLabel52.getText());
        String date = new SimpleDateFormat("yyyy-MM-dd").format(new Date());
        String paidAmount = jFormattedTextField10.getText();

        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");

        String value = jLabel72.getText();

        try {

            if (value == "0.00") {
                JOptionPane.showMessageDialog(this, "Please Select the product for GRN", "Warning", JOptionPane.WARNING_MESSAGE);
            } else {

                MySQL.executeIUD("INSERT INTO `grn` VALUES ('" + grnID + "','" + paidAmount + "','" + date + "'," + userID + ",'" + supplierID + "')");
                reset();
                genarateGRNId();
                for (GRNItem grnItem : grnItemMap.values()) {

                    ResultSet rs = MySQL.executeSearch("SELECT * FROM `stock` WHERE `selling_price` = '" + grnItem.getSprice() + "'"
                            + " AND `mf_date` = '" + sdf.format(grnItem.getMfd()) + "' AND `exp_date` = '" + sdf.format(grnItem.getExp()) + "'"
                            + " AND `product_id` = '" + grnItem.getProductId() + "'");

                    String sid = "";

                    if (rs.next()) {

                        sid = rs.getString("id");

                        String currentQTY = rs.getString("qty");
                        String updatedQuantity = String.valueOf(Double.parseDouble(currentQTY) + grnItem.getQty());
                        MySQL.executeIUD("UPDATE `stock` SET `qty` = '" + updatedQuantity + "' WHERE `id` = '" + sid + "'");
                        reset();
                        genarateGRNId();
                    } else {

                        MySQL.executeIUD("INSERT INTO `stock` (`product_id`,`qty`,`selling_price`,`mf_date`,`exp_date`)"
                                + " VALUES('" + grnItem.getProductId() + "','" + grnItem.getQty() + "','" + grnItem.getSprice() + "','" + sdf.format(grnItem.getMfd()) + "','" + sdf.format(grnItem.getExp()) + "')");

                        ResultSet rs2 = MySQL.executeSearch("SELECT * FROM `stock`"
                                + " WHERE `selling_price` = '" + grnItem.getSprice() + "'"
                                + " AND `mf_date` = '" + sdf.format(grnItem.getMfd()) + "'"
                                + " AND `exp_date` = '" + sdf.format(grnItem.getExp()) + "'"
                                + " AND `product_id` = '" + grnItem.getProductId() + "'");

                        if (rs2.next()) {
                            sid = rs2.getString("id");
                        }
                        reset();
                        genarateGRNId();
                    }

                    MySQL.executeIUD("INSERT INTO `grn_item`(`qty`,`buying_price`,`grn_id`,`stock_id`) "
                            + "VALUES('" + grnItem.getQty() + "','" + grnItem.getBprice() + "','" + grnID + "','" + sid + "')");
                    reset();
                    genarateGRNId();
                }
            }
            
        } catch (Exception e) {
            e.printStackTrace();

        }
    }//GEN-LAST:event_jButton20ActionPerformed

