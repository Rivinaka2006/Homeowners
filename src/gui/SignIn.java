    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String username = jTextField1.getText();
        String password = String.valueOf(jPasswordField1.getPassword());
        try {
            if (username.isBlank()) {
                JOptionPane.showMessageDialog(this, "Please enter your Username", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (password.isBlank()) {
                JOptionPane.showMessageDialog(this, "Please enter your Password", "Warning", JOptionPane.WARNING_MESSAGE);
            } else {
                ResultSet rs = MySQL.executeSearch("SELECT * FROM `user` WHERE `username` = '" + username + "' AND `password` ='" + password + "'");
                if (rs.next()) {
                    setEmployeeUsername(username);
                    setEmployeeID(rs.getString("id"));
                    this.dispose();
                    new HumanResourse().setVisible(true);
                } else {
                    JOptionPane.showMessageDialog(this, "Incorrect Password or Username", "Warning", JOptionPane.WARNING_MESSAGE);
                }
            }
        } catch (Exception ex) {
            ex.printStackTrace();

        }
    }//GEN-LAST:event_jButton1ActionPerformed

