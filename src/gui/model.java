    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        String model = jTextField2.getText();

        if (model.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter the Model", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {

            try {
                ResultSet rs = MySQL.executeSearch("SELECT * FROM `model` WHERE `model` = '" + model + "'");

                if (rs.next()) {
                    JOptionPane.showMessageDialog(this, "This Model already Added", "Warning", JOptionPane.WARNING_MESSAGE);
                } else {

                    MySQL.executeIUD("INSERT INTO `model` (`model`) VALUES ('" + model + "')");
                    loadTable("");
                    reset();
                    JOptionPane.showMessageDialog(this, "Model added Successfuly", "Done", JOptionPane.INFORMATION_MESSAGE);

                }
            } catch (Exception e) {
                e.printStackTrace();
            }

        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

        String id = jTextField1.getText();
        String model = jTextField2.getText();

        if (model.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please Enter the Model", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {

            try {

                ResultSet rs = MySQL.executeSearch("SELECT * FROM `model` WHERE `model` = '" + model + "'");

                if (rs.next()) {
                    JOptionPane.showMessageDialog(this, "This Model already Added", "Warning", JOptionPane.WARNING_MESSAGE);
                } else {

                    MySQL.executeIUD("UPDATE `model` SET `model` = '" + model + "' WHERE `id` = '" + id + "'");
                    loadTable("");
                    reset();
                    JOptionPane.showMessageDialog(this, "Model update Successfuly", "Done", JOptionPane.INFORMATION_MESSAGE);

                }

            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_jButton2ActionPerformed

