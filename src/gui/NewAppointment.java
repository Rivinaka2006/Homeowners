    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed

        String event = jTextField1.getText();
        Date date = jDateChooser1.getDate();
//        SimpleDateFormat format = new SimpleDateFormat("yyyy-MM-dd");
//        System.out.println(format.format(date));
        String time = jTextField2.getText();
        String guest = jTextField3.getText();
        String desc = jTextArea1.getText();

        if (event.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter Event title", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (event.length() > 45) {
            JOptionPane.showMessageDialog(this, "Please enter Event title lower than 45 characters", "Warning", JOptionPane.WARNING_MESSAGE);
        }else if (date == null) {
            JOptionPane.showMessageDialog(this, "Plese choose a date", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (time == null) {
            JOptionPane.showMessageDialog(this, "Please Pick the time", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (guest.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter your guest name", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (desc.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please describe about meeting", "Warning", JOptionPane.WARNING_MESSAGE);
        } else if (desc.length() > 200) {
            JOptionPane.showMessageDialog(this, "Description must be lower than 200 characters", "Warning", JOptionPane.WARNING_MESSAGE);
        } else {
            SimpleDateFormat format = new SimpleDateFormat("yyyy-MM-dd");
            String date1 = format.format(date);
            try {
                ResultSet resultSet = MySQL.executeSearch("SELECT * FROM `appointment` WHERE `date`='" + date1 + "' AND `time`='" + time + "'");

                if (resultSet.next()) {
                    JOptionPane.showMessageDialog(this, "You already have an appointment on this date & time", "Information", JOptionPane.INFORMATION_MESSAGE);
                } else {

                    MySQL.executeIUD("INSERT INTO `appointment`(`title`,`date`,`time`,`guest`,`description`) "
                            + "VALUES ('" + event + "','" + date1 + "','" + time + "','" + guest + "','" + desc + "')");
                    reset();
                }

            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

